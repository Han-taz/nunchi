"""Generate the regex class app_sec.strip_invisible removes from content_hmac input.

usage: python scripts/gen-unicode-ignorables.py                        print the generated block
       python scripts/gen-unicode-ignorables.py --check FILE...        compare it with FILE blocks
       python scripts/gen-unicode-ignorables.py --refresh [--ucd-dir D]   rewrite the vendored table
       python scripts/gen-unicode-ignorables.py --verify-upstream [--ucd-dir D]
                                                                       prove the table is current

The class is every code point with general category Cf, plus Default_Ignorable_Code_Point, plus
the Cc controls that are not whitespace (tab, line feed, vertical tab, form feed, carriage return
and NEL are folded to a space later instead). Postgres regular expressions have no Unicode
property classes, so the ranges are written out.

The block and --check read only scripts/data/unicode/ignorable-ranges.tsv, a table of the Cc, Cf
and Default_Ignorable_Code_Point ranges derived from the two UCD files named in
ucd-sources.sha256. They never touch the network, so the pull request check does not depend on
unicode.org. --refresh and --verify-upstream download those files (or read them from --ucd-dir),
refuse any whose sha256 differs from the pinned one, and derive the table again. --refresh writes
it. --verify-upstream exits 1 when the vendored table differs, and the nightly job runs it.
--check compares the block between the BEGIN and END marker lines of each FILE with the
generated one and exits 1 on any difference.
"""

import argparse
import hashlib
import sys
import tempfile
import urllib.request
from pathlib import Path

DATA = Path(__file__).resolve().parent / "data" / "unicode"
TABLE = DATA / "ignorable-ranges.tsv"
SOURCES = DATA / "ucd-sources.sha256"
UNICODE_VERSION = "18.0.0"
URL = "https://www.unicode.org/Public/" + UNICODE_VERSION + "/ucd/"
WHITESPACE_CONTROLS = {0x09, 0x0A, 0x0B, 0x0C, 0x0D, 0x85}
PROPERTIES = ("Cc", "Cf", "Default_Ignorable_Code_Point")
BEGIN = "-- BEGIN generated by scripts/gen-unicode-ignorables.py"
END = "-- END generated"
LINE_WIDTH = 96
BMP_MAX = 0xFFFF
TABLE_HEADER = (
    f"# Unicode {UNICODE_VERSION}: Cc, Cf and Default_Ignorable_Code_Point ranges derived\n"
    "# from the files in ucd-sources.sha256 by scripts/gen-unicode-ignorables.py --refresh.\n"
    "# property<TAB>first<TAB>last (hex code points, inclusive)\n"
)


def pinned_hashes(path: Path = SOURCES) -> dict[str, str]:
    """File name -> sha256 from sha256sum-format lines."""
    hashes: dict[str, str] = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        digest, _, name = line.partition("  ")
        hashes[name] = digest
    return hashes


def fetch(name: str, ucd_dir: Path) -> list[str]:
    path = ucd_dir / name
    if not path.exists():
        with urllib.request.urlopen(URL + name, timeout=60) as response:  # noqa: S310
            path.write_bytes(response.read())
    data = path.read_bytes()
    if hashlib.sha256(data).hexdigest() != pinned_hashes()[name]:
        sys.exit(f"{path}: sha256 differs from the pinned Unicode {UNICODE_VERSION} file")
    return data.decode("utf-8").splitlines()


def general_category(lines: list[str], wanted: set[str]) -> set[int]:
    found: set[int] = set()
    first = 0
    for line in lines:
        fields = line.split(";")
        code = int(fields[0], 16)
        if fields[1].endswith(", First>"):
            first = code
        elif fields[2] in wanted:
            found.update(range(first or code, code + 1))
            first = 0
        else:
            first = 0
    return found


def default_ignorable(lines: list[str]) -> set[int]:
    found: set[int] = set()
    for line in lines:
        body = line.split("#")[0].strip()
        if not body:
            continue
        span, _, prop = (part.strip() for part in body.partition(";"))
        if prop == "Default_Ignorable_Code_Point":
            low, _, high = span.partition("..")
            found.update(range(int(low, 16), int(high or low, 16) + 1))
    return found


def ranges(points: set[int]) -> list[tuple[int, int]]:
    merged: list[tuple[int, int]] = []
    for code in sorted(points):
        if merged and merged[-1][1] == code - 1:
            merged[-1] = (merged[-1][0], code)
        else:
            merged.append((code, code))
    return merged


def escape(code: int) -> str:
    return f"\\u{code:04x}" if code <= BMP_MAX else f"\\U{code:08x}"


def derive(ucd_dir: Path) -> dict[str, list[tuple[int, int]]]:
    """The three property range lists, read from the pinned UCD files."""
    data = fetch("UnicodeData.txt", ucd_dir)
    props = fetch("DerivedCoreProperties.txt", ucd_dir)
    return {
        "Cc": ranges(general_category(data, {"Cc"})),
        "Cf": ranges(general_category(data, {"Cf"})),
        "Default_Ignorable_Code_Point": ranges(default_ignorable(props)),
    }


def render_table(derived: dict[str, list[tuple[int, int]]]) -> str:
    rows = [
        f"{prop}\t{low:04X}\t{high:04X}\n" for prop in PROPERTIES for low, high in derived[prop]
    ]
    return TABLE_HEADER + "".join(rows)


def read_table(path: Path) -> dict[str, list[tuple[int, int]]]:
    derived: dict[str, list[tuple[int, int]]] = {prop: [] for prop in PROPERTIES}
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("#"):
            continue
        prop, low, high = line.split("\t")
        derived[prop].append((int(low, 16), int(high, 16)))
    return derived


def block(derived: dict[str, list[tuple[int, int]]]) -> str:
    def points(prop: str) -> set[int]:
        return {code for low, high in derived[prop] for code in range(low, high + 1)}

    kept = (
        (points("Cc") - WHITESPACE_CONTROLS) | points("Cf") | points("Default_Ignorable_Code_Point")
    )
    items = [
        escape(low) if low == high else f"{escape(low)}-{escape(high)}"
        for low, high in ranges(kept)
    ]
    chunks: list[str] = [""]
    for item in items:
        if len(chunks[-1]) + len(item) > LINE_WIDTH:
            chunks.append("")
        chunks[-1] += item
    last = len(chunks) - 1
    quoted = [
        ("'[" if i == 0 else "|| '") + chunk + ("]'" if i == last else "'")
        for i, chunk in enumerate(chunks)
    ]
    return "\n".join([f"{BEGIN} (Unicode {UNICODE_VERSION})", *quoted, END])


def extract(path: Path) -> str:
    lines = path.read_text(encoding="utf-8").splitlines()
    start = next((i for i, x in enumerate(lines) if x.strip().startswith(BEGIN)), None)
    stop = next((i for i, x in enumerate(lines) if x.strip() == END), None)
    if start is None or stop is None or stop < start:
        sys.exit(f"{path}: no '{BEGIN}' ... '{END}' block")
    return "\n".join(x.strip() for x in lines[start : stop + 1])


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--table", type=Path, default=TABLE)
    parser.add_argument("--ucd-dir", type=Path)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", nargs="+", type=Path, metavar="FILE")
    mode.add_argument("--refresh", action="store_true")
    mode.add_argument("--verify-upstream", action="store_true")
    args = parser.parse_args()
    if args.refresh or args.verify_upstream:
        with tempfile.TemporaryDirectory() as tmp:
            table = render_table(derive(args.ucd_dir or Path(tmp)))
        if args.refresh:
            args.table.write_text(table, encoding="utf-8")
        elif args.table.read_text(encoding="utf-8") != table:
            sys.stderr.write(f"{args.table}: differs from the table derived from unicode.org\n")
            return 1
        return 0
    generated = block(read_table(args.table))
    if args.check is None:
        sys.stdout.write(generated + "\n")
        return 0
    status = 0
    for path in args.check:
        if extract(path) != generated:
            sys.stderr.write(f"{path}: generated block is stale; rerun without --check\n")
            status = 1
    return status


if __name__ == "__main__":
    sys.exit(main())
