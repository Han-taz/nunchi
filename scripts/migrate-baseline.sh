#!/usr/bin/env bash
# Regenerate db/migrations/0001_baseline.sql from db/schema.sql.
# Only valid while 0001 is unapplied everywhere. After that, schema.sql changes
# ship as new numbered migrations and this script must not be run again.
set -euo pipefail

repo_root=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
out="$repo_root/db/migrations/0001_baseline.sql"
mkdir -p "$repo_root/db/migrations"
{
  echo "-- Generated by scripts/migrate-baseline.sh from db/schema.sql. Do not edit by hand."
  cat "$repo_root/db/schema.sql"
} >"$out"
echo "wrote $out"
